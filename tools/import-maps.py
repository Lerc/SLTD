#!/usr/bin/env python3
"""Import the 11 × 16 map PNGs into maps.js. Requires Pillow; --check is read-only."""
import argparse
import json
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
ROAD, ENTRY, EXIT = (178, 132, 190), (59, 122, 87), (211, 33, 45)
GROUND = {(0, 0, 0), (27, 24, 17)}
MAPS = [
    ('knotwork', 'Knotwork', 'Two crossings link tight loops. Cover the center on both passes.'),
    ('zigzag', 'Zigzag', 'Enter top right. Follow the staggered bends into long southern lanes.'),
    ('coil', 'Coil', 'Enter from the west, circle the outer rim, then return to the western exit.'),
    ('longbow', 'Longbow', 'Enter from the east. Round the southern bend before the long climb north.'),
    ('serpentine', 'Serpentine', 'Long parallel lanes fold inward from the top-right entrance.'),
    ('cascade', 'Cascade', 'Climb from the bottom through narrow bends to the top-right exit.'),
    ('sawtooth', 'Sawtooth', 'Enter bottom left. Climb through two rows of alternating bends.'),
    ('interlace', 'Interlace', 'Six crossings weave the route together. Cover the repeated passes.'),
]
BEGIN, END = '// BEGIN PNG MAPS', '// END PNG MAPS'


def trace_png(filename):
    with Image.open(filename) as image:
        if image.size != (11, 16):
            raise ValueError(f'{filename}: expected 11 × 16 pixels')
        pixels = image.convert('RGB')
        colors = {(x, y): pixels.getpixel((x, y)) for y in range(16) for x in range(11)}
    if set(colors.values()) - GROUND - {ROAD, ENTRY, EXIT}:
        raise ValueError(f'{filename}: unrecognized map color')
    road = {p for p, color in colors.items() if color in (ROAD, ENTRY, EXIT)}

    def neighbours(p):
        x, y = p
        return [n for n in ((x-1, y), (x+1, y), (x, y-1), (x, y+1)) if n in road]

    ends = sorted((p for p in road if len(neighbours(p)) == 1), key=lambda p: (p[1], p[0]))
    entries = [p for p in road if colors[p] == ENTRY]
    exits = [p for p in road if colors[p] == EXIT]
    if len(ends) != 2 or any(len(neighbours(p)) not in (1, 2, 4) for p in road):
        raise ValueError(f'{filename}: route needs two ends and only straight crossings')
    if entries or exits:
        if len(entries) != 1 or len(exits) != 1 or set(entries + exits) != set(ends):
            raise ValueError(f'{filename}: green/red markers must mark the two ends')
        start, finish = entries[0], exits[0]
    else:
        start, finish = ends  # Unmarked maps enter at the topmost endpoint.

    def outside(p):
        n = neighbours(p)[0]
        q = (2*p[0]-n[0], 2*p[1]-n[1])
        if 0 <= q[0] < 11 and 0 <= q[1] < 16:
            raise ValueError(f'{filename}: endpoint does not lead off the board')
        return q

    path = [outside(start), start]
    traversed = set()
    while path[-1] != finish:
        prev, p = path[-2:]
        choices = [n for n in neighbours(p) if n != prev]
        if len(choices) == 3:
            choices = [(2*p[0]-prev[0], 2*p[1]-prev[1])]
        if len(choices) != 1 or choices[0] not in road:
            raise ValueError(f'{filename}: ambiguous turn at {p}')
        edge = (p, choices[0])
        if edge in traversed:
            raise ValueError(f'{filename}: route loops without reaching the exit')
        traversed.add(edge)
        path.append(choices[0])
    if set(path[1:]) != road:
        raise ValueError(f'{filename}: route leaves road pixels unvisited')
    path.append(outside(finish))
    # Keep only corners; traceRoute restores every unit step at runtime.
    points = [path[0]]
    for a, b, c in zip(path, path[1:], path[2:]):
        if (b[0]-a[0], b[1]-a[1]) != (c[0]-b[0], c[1]-b[1]):
            points.append(b)
    return points + [path[-1]]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if generated routes are out of date')
    args = parser.parse_args()
    lines = [BEGIN, '// Generated by tools/import-maps.py; green enters, red exits, crossings go straight.',
             'const patternMaps = [']
    for i, (map_id, name, description) in enumerate(MAPS, 1):
        source = f'BaseMedia/Maps/map{i}.png'
        route = trace_png(ROOT / source)
        fields = dict(id=map_id, name=name, description=description, source=source)
        lines += ['  {', '    ' + ', '.join(f'{k}: {json.dumps(v)}' for k, v in fields.items()) + ',',
                  '    route: ' + json.dumps(route, separators=(',', ':')), '  },']
    lines += ['].map(({route, ...map}) => ({...map, cells:routeMap(route), path:traceRoute(route)}));', END]
    generated = '\n'.join(lines)
    target = ROOT / 'srv/maps.js'
    current = target.read_text()
    before, rest = current.split(BEGIN, 1)
    _, after = rest.split(END, 1)
    updated = before + generated + after
    if args.check:
        if updated != current:
            raise SystemExit('PNG maps are out of date: run python3 tools/import-maps.py')
        print('PASS all eight PNG layouts match their generated routes')
    else:
        target.write_text(updated)
        print('Imported eight PNG maps into srv/maps.js')


if __name__ == '__main__':
    main()
